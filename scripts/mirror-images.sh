#!/usr/bin/env bash
# Copy every image the stack runs into a registry your cluster CAN reach, and
# generate an overlay that points at the copies. For clusters that cannot pull
# from ghcr.io or Docker Hub.
#
#   scripts/mirror-images.sh registry.example.com/team/secure-notes
#   KUBECTL=oc scripts/k8s-deploy.sh deploy/k8s/overlays/mirror
#
# Log in to the destination first (skopeo login / podman login / oc registry login).
#
# Env:
#   MIRROR_TOOL=skopeo|oc    default: skopeo if installed, else `oc image mirror`
#   TAG=latest               tag of the published app and aws-mock images to copy
#   BASE_OVERLAY=openshift   overlay the generated one builds on (openshift or kind)
#   DEST_TLS_VERIFY=true     false only for a lab registry without a trusted certificate
#   SRC_APP, SRC_MOCK, SRC_POSTGRES, SRC_REDIS
#                            override a source, in skopeo transport syntax
#                            (CI copies straight from the local Docker daemon:
#                            docker-daemon:secure-notes-app:dev)
set -euo pipefail
cd "$(dirname "$0")/.."
# shellcheck disable=SC1091
. scripts/versions.env

DEST="${1:?usage: scripts/mirror-images.sh <registry>/<path>   e.g. quay.example.com/team/secure-notes}"
DEST="${DEST%/}"
TAG="${TAG:-latest}"
BASE_OVERLAY="${BASE_OVERLAY:-openshift}"
TLS="${DEST_TLS_VERIFY:-true}"
GHCR="ghcr.io/ephico2real2/openbao-node-poc"
TOOL="${MIRROR_TOOL:-$(command -v skopeo >/dev/null && echo skopeo || echo oc)}"

pg_tag="${POSTGRES_IMAGE##*:}"
redis_tag="${REDIS_IMAGE##*:}"

# source | destination | name in the manifests (what kustomize rewrites)
plan=(
  "${SRC_APP:-docker://$GHCR/app:$TAG}|$DEST/secure-notes-app:$TAG"
  "${SRC_MOCK:-docker://$GHCR/aws-mock:$TAG}|$DEST/secure-notes-aws-mock:$TAG"
  "${SRC_POSTGRES:-docker://$POSTGRES_IMAGE}|$DEST/postgres:$pg_tag"
  "${SRC_REDIS:-docker://$REDIS_IMAGE}|$DEST/redis:$redis_tag"
)

echo "== mirroring with $TOOL to $DEST"
for line in "${plan[@]}"; do
  src="${line%%|*}" dst="${line##*|}"
  echo "  $src -> $dst"
  case "$TOOL" in
    skopeo)
      # --all keeps every architecture of a multi-arch image, and with it the digests.
      all=(--all); [[ "$src" == docker-daemon:* ]] && all=()
      skopeo copy -q "${all[@]}" --dest-tls-verify="$TLS" "$src" "docker://$dst"
      ;;
    oc)
      [[ "$src" == docker://* ]] || { echo "oc image mirror needs a registry source, got $src"; exit 1; }
      insecure=(); [ "$TLS" = false ] && insecure=(--insecure)
      oc image mirror "${insecure[@]}" --keep-manifest-list=true "${src#docker://}=$dst"
      ;;
    *) echo "MIRROR_TOOL must be skopeo or oc"; exit 1 ;;
  esac
done

# The overlay: the chosen one, with every image name rewritten to the mirror.
out=deploy/k8s/overlays/mirror
mkdir -p "$out"
cat > "$out/kustomization.yaml" <<YAML
# GENERATED by scripts/mirror-images.sh (not committed): overlays/$BASE_OVERLAY
# with every image pulled from $DEST.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ../$BASE_OVERLAY
images:
  # the names the $BASE_OVERLAY overlay uses (published, then local build names)
  - { name: $GHCR/app, newName: $DEST/secure-notes-app, newTag: "$TAG" }
  - { name: $GHCR/aws-mock, newName: $DEST/secure-notes-aws-mock, newTag: "$TAG" }
  - { name: secure-notes-app, newName: $DEST/secure-notes-app, newTag: "$TAG" }
  - { name: secure-notes-aws-mock, newName: $DEST/secure-notes-aws-mock, newTag: "$TAG" }
  - { name: ${POSTGRES_IMAGE%:*}, newName: $DEST/postgres, newTag: "$pg_tag" }
  - { name: ${REDIS_IMAGE%:*}, newName: $DEST/redis, newTag: "$redis_tag" }
YAML

# Prove it: every image the overlay renders must come from the mirror.
kz() { if command -v kubectl >/dev/null; then kubectl kustomize "$1"; else kustomize build "$1"; fi; }
mapfile -t images < <(kz "$out" | sed -n 's/^ *image: *//p' | tr -d '"' | sort -u)
bad=0
for i in "${images[@]}"; do
  if [[ "$i" == "$DEST/"* ]]; then echo "  ok    $i"; else echo "  FAIL  $i is not from $DEST"; bad=1; fi
done
[ "$bad" = 0 ] || exit 1
echo "== wrote $out — deploy with:  KUBECTL=oc scripts/k8s-deploy.sh $out"
